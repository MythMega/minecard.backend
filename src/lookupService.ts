/**
 * Player lookup by pseudo or UUID ("Retrouver un joueur") - MineCards backend.
 *
 * The trainer-card pseudo is UNIQUE (`sql/schema/10-username-unique.sql`), so it
 * designates exactly one account and can be used wherever the game used to ask
 * for the UUID: adding a friend, loading an online save. The client cannot know
 * the UUID of somebody it only knows by name, and the other routes (`/cards`,
 * `/saves/last`) are keyed by UUID: this route is the one translation between
 * the two, and it stays the ONLY place that maps a pseudo to an account.
 *
 * `GET /lookup?query=<pseudo|uuid>`
 *   The shape of the field decides how it is read, so the game never has to ask
 *   the player which kind of identifier they typed:
 *     - a v4 UUID is read as an UUID (an exact, lowercased match);
 *     - anything else is read as a pseudo, with `COLLATE NOCASE`, so `steve`
 *       finds `Steve` (the same rule the unique index enforces).
 *
 *   Answers `200 { found: true, uuid, username }` or `200 { found: false }`:
 *   "nobody uses this pseudo" is a legitimate answer to a lookup, not a failure,
 *   so the game shows its own message instead of decoding an HTTP error.
 *
 *   A pseudo only exists once its owner published a trainer card (`cards` row),
 *   which is exactly why this route reads `cards` and not `users`: an account
 *   that only uploaded a save has no public identity, and is reachable by UUID.
 *
 * The route is public, like `GET /cards`: a pseudo and the card it designates are
 * public by design. It never returns the secret code, and it authorizes nothing:
 * an online save still needs the `uuid` + `auth_code` pair.
 *
 * Reference: `src/cardService.ts` and `doc/lookup.md`.
 */

/** Shape of a v4 UUID, as generated by the game. */
const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;

/**
 * Maximum length of a typed pseudo, in characters.
 *
 * Both halves MUST agree: `PROFILE_NAME_MAX_LENGTH` in the game's
 * `ProfileManager.js` refuses a longer display name, so no stored pseudo is
 * longer than this. A longer query is answered like an unknown player rather than
 * sent to the database.
 */
export const MAX_USERNAME_LENGTH = 24;

/** One account, reduced to what a lookup returns. */
export interface PlayerIdentity {
  uuid: string;
  username: string;
}

/** Result of one lookup route, wrapped into a JSON response by `index.ts`. */
export interface LookupRouteResult {
  status: number;
  body: unknown;
}

/**
 * Reads one account by UUID.
 *
 * @param {D1Database} db - D1 binding.
 * @param {string} uuid - Lowercased v4 UUID.
 * @returns {Promise<PlayerIdentity|null>} The account, or null when no card was published.
 */
async function readByUuid(db: D1Database, uuid: string): Promise<PlayerIdentity | null> {
  const row = await db
    .prepare("SELECT uuid, username FROM cards WHERE uuid = ?")
    .bind(uuid)
    .first<PlayerIdentity>();
  return row ?? null;
}

/**
 * Reads one account by pseudo, case-insensitively.
 *
 * @param {D1Database} db - D1 binding.
 * @param {string} username - Pseudo as typed by the player.
 * @returns {Promise<PlayerIdentity|null>} The account, or null when the pseudo is free.
 */
async function readByUsername(
  db: D1Database,
  username: string
): Promise<PlayerIdentity | null> {
  const row = await db
    .prepare("SELECT uuid, username FROM cards WHERE username = ? COLLATE NOCASE")
    .bind(username)
    .first<PlayerIdentity>();
  return row ?? null;
}

/**
 * Resolves a typed pseudo or UUID to the account it designates.
 *
 * Shared by the route below and by any other service that may receive either
 * kind of identifier, so the detection rule lives in one place.
 *
 * @param {D1Database} db - D1 binding.
 * @param {unknown} value - Raw identifier (pseudo or UUID).
 * @returns {Promise<PlayerIdentity|null>} The account, or null when nobody matches.
 */
export async function findPlayer(db: D1Database, value: unknown): Promise<PlayerIdentity | null> {
  const text = typeof value === "string" ? value.trim() : "";
  if (text === "" || text.length > Math.max(MAX_USERNAME_LENGTH, 36)) return null;

  const lower = text.toLowerCase();
  if (UUID_PATTERN.test(lower)) return readByUuid(db, lower);
  if (text.length > MAX_USERNAME_LENGTH) return null;
  return readByUsername(db, text);
}

/**
 * `GET /lookup` - translates a pseudo or a UUID into the account it designates.
 *
 * @param {Request} request - Incoming request.
 * @param {D1Database} db - D1 binding.
 * @returns {Promise<LookupRouteResult>} The result.
 */
async function lookupPlayer(request: Request, db: D1Database): Promise<LookupRouteResult> {
  const url = new URL(request.url);
  const query = (url.searchParams.get("query") ?? "").trim();

  if (query === "") {
    return { status: 400, body: { error: "Le champ 'query' (pseudo ou UUID) est requis." } };
  }
  if (query.length > Math.max(MAX_USERNAME_LENGTH, 36)) {
    return {
      status: 400,
      body: { error: `Le champ 'query' accepte au plus ${MAX_USERNAME_LENGTH} caractères (pseudo).` },
    };
  }

  const player = await findPlayer(db, query);
  if (!player) {
    return { status: 200, body: { found: false } };
  }
  return {
    status: 200,
    body: { found: true, uuid: player.uuid, username: player.username },
  };
}

/**
 * Answers the lookup route.
 *
 * @param {Request} request - Incoming request.
 * @param {D1Database} db - D1 binding.
 * @param {string} path - Normalized pathname (no trailing slash).
 * @returns {Promise<LookupRouteResult|null>} The result, or null when the path is not a lookup route.
 */
export async function handleLookupRequest(
  request: Request,
  db: D1Database,
  path: string
): Promise<LookupRouteResult | null> {
  if (path !== "/lookup") return null;
  if (request.method !== "GET") {
    return { status: 405, body: { error: "Méthode non autorisée." } };
  }
  return lookupPlayer(request, db);
}
